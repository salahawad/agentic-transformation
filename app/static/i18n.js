function localizeError(detail) {
  if (typeof detail !== "string") return "";
  const tool = detail.match(/^Add (.+) to your tools before using it in a workflow\.$/s);
  return tool ? tr("Add {0} to your tools before using it in a workflow.", tool[1]) : tr(detail);
}
function validationMessage(error) {
  const context = error.ctx || {};
  const messages = {
    string_too_short: ["Use at least {0} characters.", context.min_length],
    string_too_long: ["Use at most {0} characters.", context.max_length],
    too_short: ["Add at least {0} items.", context.min_length],
    too_long: ["Use at most {0} items.", context.max_length],
    greater_than_equal: ["Enter a value of at least {0}.", context.ge],
    greater_than: ["Enter a value greater than {0}.", context.gt],
    less_than_equal: ["Enter a value of at most {0}.", context.le],
    less_than: ["Enter a value less than {0}.", context.lt],
    missing: ["This field is required."],
  };
  const message = messages[error.type];
  const description = message
    ? tr(...message)
    : error.type === "value_error"
      ? localizeError(error.msg.replace(/^Value error, /, ""))
      : language === "fr" ? tr("Check this value.") : error.msg;
  const fields = {
    name: "Name", email: "Work email", role: "Role / job title", team_id: "Team",
    entity_id: "Entity", category: "Category", tools: "Tools", workflows: "Workflows",
    steps: "Steps", action: "Action", tool: "Tool", minutes: "Minutes / run",
    support: "Agent support", human_review: "Human review", frequency_count: "Number of times",
    frequency_unit: "Frequency period", runs_per_week: "Runs per week", notes: "Notes",
    password: "Workspace password", trigger: "Trigger", outcome: "Outcome", pain_points: "Friction",
  };
  const path = error.loc.slice(1).map((field) =>
    typeof field === "number" ? field + 1 : tr(fields[field] || "Field"),
  ).join(" → ");
  return `${path}: ${description}`;
}
