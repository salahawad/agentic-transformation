let language = "en";
try {
  const saved = localStorage.getItem("atlas_language");
  language = ["en", "fr"].includes(saved)
    ? saved
    : navigator.language.toLowerCase().startsWith("fr") ? "fr" : "en";
} catch {
  language = navigator.language.toLowerCase().startsWith("fr") ? "fr" : "en";
}
function tr(key, ...values) {
  const text = language === "fr" && Object.hasOwn(french, key) ? french[key] : key;
  return text.replace(/\{(\d+)\}/g, (_, index) => String(values[+index] ?? ""));
}
function currentLocale() {
  return language === "fr" ? "fr-FR" : "en-GB";
}
function formatNumber(value, digits) {
  return Number(value).toLocaleString(currentLocale(), {
    minimumFractionDigits: digits ?? 0,
    maximumFractionDigits: digits ?? 20,
  });
}
function setLanguage(value) {
  language = value === "fr" ? "fr" : "en";
  try {
    localStorage.setItem("atlas_language", language);
  } catch {
    // The current page still works when browser storage is disabled.
  }
  applyLanguageMetadata();
}
function applyLanguageMetadata() {
  document.documentElement.lang = language;
  document.title = tr("Agent Atlas · Transformation workspace");
  document.querySelector('meta[name="description"]').content = tr(
    "Map your people's tools and workflows. Turn everyday work into a practical roadmap for helpful agents.",
  );
  const loading = document.querySelector(".loading");
  if (loading) loading.textContent = tr("Opening your workspace…");
}
